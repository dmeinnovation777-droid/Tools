def config_dir() -> str:
    """Per-user settings folder for every DME tool."""
    if os.name == "nt":
        base = os.environ.get("APPDATA") or os.path.expanduser("~")
    elif sys.platform == "darwin":
        base = os.path.expanduser("~/Library/Application Support")
    else:
        base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return os.path.join(base, VENDOR)


def write_ico(path: str) -> str:
    """Write the embedded .ico to disk and return the path (used by build scripts)."""
    with open(path, "wb") as f:
        f.write(base64.b64decode(ICON_ICO_B64))
    return path


def apply_window_icon(window) -> None:
    """Set the taskbar / title bar icon on a tkinter window. Never raises."""
    import tkinter as tk

    try:
        ico_path = os.path.join(tempfile.gettempdir(), "dme_innovation_icon.ico")
        if not os.path.exists(ico_path):
            write_ico(ico_path)
        window.iconbitmap(ico_path)
    except Exception:
        pass
    try:
        img = tk.PhotoImage(data=ICON_PNG_B64)
        window.iconphoto(True, img)
        window._dme_icon_ref = img  # keep a reference alive
    except Exception:
        pass


HEADER_LOGOS = {40: "LOGO_HEADER_40_B64", 60: "LOGO_HEADER_60_B64",
                80: "LOGO_HEADER_80_B64"}


def header_logo(parent, scale: float = 1.0):
    """
    Return a Label holding the wordmark, or None if the image cannot load.

    The largest baked-in size that still fits is used as-is. Tk can only scale
    bitmaps by whole factors, so picking a ready-made size keeps the wordmark
    sharp instead of blocky.
    """
    import tkinter as tk

    target = 40 * max(scale, 1.0)
    fitting = [h for h in sorted(HEADER_LOGOS) if h <= target + 0.5]
    height = fitting[-1] if fitting else min(HEADER_LOGOS)
    try:
        img = tk.PhotoImage(data=globals()[HEADER_LOGOS[height]])
        lbl = tk.Label(parent, image=img, bg=HEADER_BG, bd=0)
        lbl.image = img
        return lbl
    except Exception:
        return None
